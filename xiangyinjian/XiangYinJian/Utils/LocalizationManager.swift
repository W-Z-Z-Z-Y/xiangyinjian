import SwiftUI
import Combine

// MARK: - 语言枚举

enum AppLanguage: String, CaseIterable, Identifiable {
    case zh = "zh"
    case en = "en"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .zh: return "中文"
        case .en: return "English"
        }
    }
}

// MARK: - 语言管理器

final class LanguageManager: ObservableObject {
    static let shared = LanguageManager()

    @Published var current: AppLanguage {
        didSet {
            UserDefaults.standard.set(current.rawValue, forKey: "appLanguage")
        }
    }

    private init() {
        let saved = UserDefaults.standard.string(forKey: "appLanguage") ?? "zh"
        self.current = AppLanguage(rawValue: saved) ?? .zh
    }

    /// 日期语言跟随 App 设置，不跟随手机系统的语言。
    func memoryDate(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.calendar = Calendar(identifier: .gregorian)
        if current == .zh {
            let parts = formatter.calendar.dateComponents([.year, .month, .day], from: date)
            guard let year = parts.year, let month = parts.month, let day = parts.day else { return "" }
            return "\(year)年\(month)月\(day)日"
        }
        formatter.locale = Locale(identifier: "en_US")
        formatter.dateFormat = "MMMM d, yyyy"
        return formatter.string(from: date)
    }

    /// 翻译函数
    func tr(_ key: String) -> String {
        Self.strings[current.rawValue]?[key]
            ?? Self.strings["zh"]?[key]
            ?? key
    }

    /// 方言名称翻译（用于 UI 显示，内部存储仍用中文键）
    func dialectDisplayName(_ name: String) -> String {
        let canonicalName = name == "闽南话" ? "闽南语" : name
        return tr("dialect.\(canonicalName)")
    }

